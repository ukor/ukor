document.addEventListener('DOMContentLoaded', () => {
  document.querySelectorAll('.highlight').forEach((highlightDiv) => {
    const button = document.createElement('button');
    button.className = 'copy-code-btn';
    button.type = 'button';
    button.innerText = 'Copy';
    button.setAttribute('aria-label', 'Copy code to clipboard');

    button.addEventListener('click', () => {
      const codeBlock = highlightDiv.querySelector('code');
      if (!codeBlock) return;

      navigator.clipboard.writeText(codeBlock.innerText).then(() => {
        button.innerText = 'Copied!';
        setTimeout(() => {
          button.innerText = 'Copy';
        }, 2000);
      }).catch((err) => {
        console.error('Failed to copy code: ', err);
        button.innerText = 'Error';
      });
    });

    // Make the parent highlight div relative so the button can be positioned absolutely
    highlightDiv.style.position = 'relative';
    highlightDiv.appendChild(button);
  });
});
